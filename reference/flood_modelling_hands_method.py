# 1. STRICT REMOVAL OF PRIOR RENAMED FILES (Matches ONLY '0.50m.tif', '1.25m.tif', etc.)
# Regex pattern explained:
# ^          = start of filename
# \d+\.\d+   = one or more digits, a literal dot, one or more digits
# m\.tif$    = literal 'm.tif' at the very end
strict_renamed_pattern = re.compile(r"^\d+\.\d+m\.tif$")

for f in os.listdir("."):
    if strict_renamed_pattern.match(f) or f == zip_filename:
        try:
            os.remove(f)
            print(f"Removed prior target file: {f}")
        except OSError as e:
            print(f"Error removing {f}: {e}")

# 2. LOCATE ORIGINAL INPUT FILES
depths = glob.glob("hand_depth_stage*tif")
renamed_files = []

# 3. RENAME INPUT FILES TO DEPTH ONLY (e.g., depth_display_stage_0.50m.tif -> 0.50m.tif)
for file_path in depths:
    dir_name, file_name = os.path.split(file_path)
    match = re.search(r"(\d+\.\d+m)", file_name)
    if match:
        new_name = f"{match.group(1)}.tif"
    else:
        new_name = file_name.replace("depth_display_stage_", "")

    new_path = os.path.join(dir_name, new_name)
    os.rename(file_path, new_path)
    renamed_files.append(new_path)

