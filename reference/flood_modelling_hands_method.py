def pick_stream_threshold(acc, frac=0.3):
    """Choose a threshold so that approximately `frac` of pixels are streams."""
    a = acc.astype("float32")
    a[~np.isfinite(a)] = np.nan
    q = 100 * (1 - frac)
    thr = np.nanpercentile(a, q)
    return thr

