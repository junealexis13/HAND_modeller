def clip_dem_to_aoi(dem_path, aoi_ee, out_path="/content/dem_aoi.tif"):
    """Clips a local DEM (GeoTIFF) to an Earth Engine Geometry (AOI)."""
    aoi_geom = eegeom_to_geojson_geom(aoi_ee)

    with rasterio.open(dem_path) as src:
        src_crs = src.crs

        # AOI from geemap is usually EPSG:4326; transform if DEM CRS differs
        geom_for_mask = aoi_geom
        # Check if the AOI CRS is different from the DEM CRS and transform if needed
        if src_crs and str(src_crs).lower() not in ["epsg:4326", "wgs84"] and aoi_geom['type'] != 'Point': # Points don't need transformation for masking
            # Fiona expects a list of geometries for masking
            geom_for_mask = transform_geom("EPSG:4326", src_crs, aoi_geom)

        out_img, out_transform = mask(src, [geom_for_mask], crop=True)
        out_meta = src.meta.copy()

    out_meta.update({
        "height": out_img.shape[1],
        "width": out_img.shape[2],
        "transform": out_transform,
        "compress": "LZW"
    })

    with rasterio.open(out_path, "w", **out_meta) as dst:
        dst.write(out_img)

    return out_path

