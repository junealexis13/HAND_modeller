def depth_tif_to_data_url(depth_path, stage_m, cmap_name="turbo"):
    """
    Converts a flood-depth GeoTIFF into an RGBA PNG data URL.

    Pixels with no flooding or nodata become fully transparent.
    Flooded pixels are colored according to depth.
    """
    with rasterio.open(depth_path) as src:
        depth = src.read(1).astype("float32")
        nodata = src.nodata
        bounds = src.bounds

    valid = np.isfinite(depth)

    if nodata is not None:
        valid &= depth != nodata

    # Only positive inundation depth should be visible
    valid &= depth > 0

    # Normalize depth to 0–1 using the corresponding stage
    normalized = np.zeros_like(depth, dtype=np.float32)
    normalized[valid] = np.clip(depth[valid] / float(stage_m), 0, 1)

    cmap = plt.get_cmap(cmap_name)
    rgba = (cmap(normalized) * 255).astype(np.uint8)

    rgba[..., 3] = np.where(valid, 220, 0).astype(np.uint8)

    # Raster row zero is north/top, which is correct for ImageOverlay
    image = Image.fromarray(rgba, mode="RGBA")

    buffer = io.BytesIO()
    image.save(buffer, format="PNG")

    encoded = base64.b64encode(buffer.getvalue()).decode("utf-8")
    data_url = f"data:image/png;base64,{encoded}"

    leaflet_bounds = [
        [bounds.bottom, bounds.left],
        [bounds.top, bounds.right]
    ]

    return data_url, leaflet_bounds

