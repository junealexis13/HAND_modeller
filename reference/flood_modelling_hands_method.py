def extract_shp_from_zip(zip_path, extract_dir):
    """
    Extracts a zip file and locates the main .shp file path.
    """
    with zipfile.ZipFile(zip_path, 'r') as zip_ref:
        zip_ref.extractall(extract_dir)

    # Search for the .shp file inside the extracted files
    for root, _, files_list in os.walk(extract_dir):
        for file in files_list:
            if file.lower().endswith('.shp'):
                return os.path.join(root, file)
    return None

def get_aoi_from_file(uploaded_file_path):
    """
    Dynamically determines file type (.kml or .zip shapefile),
    parses geometry using fiona, and converts it to an ee.Geometry.
    """
    target_path = uploaded_file_path

    # Handle Zipped Shapefiles dynamically
    if uploaded_file_path.lower().endswith('.zip'):
        temp_dir = tempfile.mkdtemp()
        shp_path = extract_shp_from_zip(uploaded_file_path, temp_dir)
        if not shp_path:
            print("Error: No valid .shp file found inside the uploaded ZIP archive.")
            return None
        target_path = shp_path

    try:
        # Fiona automatically handles KML driver and SHP driver based on file extension
        with fiona.open(target_path, 'r') as source:
            if len(source) == 0:
                print(f"Warning: No features found in {target_path}")
                return None

            # Combine all features into a single geometry if multiple exist
            geoms = [shape(feature['geometry']) for feature in source if feature.get('geometry')]
            if not geoms:
                print("Warning: No valid geometries found.")
                return None

            # If there's only one feature, use it; otherwise, unary_union merges multi-polygons/features
            if len(geoms) == 1:
                combined_geom = geoms[0]
            else:
                from shapely.ops import unary_union
                combined_geom = unary_union(geoms)

            # Convert to ee.Geometry
            if combined_geom.geom_type == 'Point':
                return ee.Geometry.Point(list(combined_geom.coords)[0])
            else:
                return ee.Geometry(combined_geom.__geo_interface__)

    except Exception as e:
        print(f"Error processing file {uploaded_file_path}: {e}")
        return None

