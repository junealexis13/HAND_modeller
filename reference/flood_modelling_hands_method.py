def reproject_to_epsg4326(input_path, output_path=None):
    """
    Reprojects a GeoTIFF to EPSG:4326 (WGS 84).
    Returns the output filepath and geographic bounds formatted for ipyleaflet.
    """
    if output_path is None:
        temp_dir = tempfile.gettempdir()
        output_path = os.path.join(temp_dir, f"reprojected_{os.path.basename(input_path)}")

    dst_crs = 'EPSG:4326'

    with rasterio.open(input_path) as src:
        transform, width, height = calculate_default_transform(
            src.crs, dst_crs, src.width, src.height, *src.bounds
        )
        kwargs = src.meta.copy()
        kwargs.update({
            'crs': dst_crs,
            'transform': transform,
            'width': width,
            'height': height
        })

        with rasterio.open(output_path, 'w', **kwargs) as dst:
            for i in range(1, src.count + 1):
                reproject(
                    source=rasterio.band(src, i),
                    destination=rasterio.band(dst, i),
                    src_transform=src.transform,
                    src_crs=src.crs,
                    dst_transform=transform,
                    dst_crs=dst_crs,
                    resampling=Resampling.bilinear
                )

    # Re-open reprojected raster to compute exact geographic bounds
    with rasterio.open(output_path) as reprojected_src:
        b = reprojected_src.bounds
        # ipyleaflet bounds: [[south, west], [north, east]]
        bounds_4326 = [[b.bottom, b.left], [b.top, b.right]]

    return output_path, bounds_4326

