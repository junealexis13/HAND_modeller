def compute_hand_from_dem(dem_path, streams_acc_threshold=2000, out_hand="/content/hand.tif"):
    grid = Grid.from_raster(dem_path)
    dem  = grid.read_raster(dem_path)
    dem = grid.fill_pits(dem)
    dem = grid.fill_depressions(dem)
    dem = grid.resolve_flats(dem)
    fdir = grid.flowdir(dem)
    acc  = grid.accumulation(fdir)
    streams = acc > streams_acc_threshold
    hand = grid.compute_hand(fdir, dem, streams)
    grid.to_raster(hand, out_hand)
    return out_hand

